// Regenerates lib/sounds/catalog.data.ts from the sample manifests the engine loads.
// Run with: node scripts/gen-sound-catalog.mjs
import { writeFileSync } from 'node:fs';

const CDN = 'https://strudel.b-cdn.net';
const get = async (f) => (await fetch(`${CDN}/${f}`)).json();

const machines = await get('tidal-drum-machines.json');
const aliases = await get('tidal-drum-machines-alias.json');
const uzu = await get('uzu-drumkit.json');

const banks = {};
for (const [key, files] of Object.entries(machines)) {
  const sep = key.lastIndexOf('_');
  if (key === '_base' || sep <= 0 || sep === key.length - 1) continue;
  (banks[key.slice(0, sep)] ??= {})[key.slice(sep + 1)] = files.length;
}
const defaultKit = Object.fromEntries(Object.entries(uzu).filter(([k]) => k !== '_base').map(([k, v]) => [k, v.length]));

const out = `// Generated by scripts/gen-sound-catalog.mjs from ${CDN}. Do not edit by hand.

/** Drum-machine bank → sound → number of variants. */
export const BANKS: Record<string, Record<string, number>> = ${JSON.stringify(banks, null, 2)};

/** Short alias names Strudel also accepts for each bank. */
export const BANK_ALIASES: Record<string, string> = ${JSON.stringify(aliases, null, 2)};

/** Sounds with no .bank(): sound → number of variants. */
export const DEFAULT_KIT: Record<string, number> = ${JSON.stringify(defaultKit, null, 2)};
`;
writeFileSync(new URL('../lib/sounds/catalog.data.ts', import.meta.url), out);
console.log(`${Object.keys(banks).length} banks`);
